// Shared KEY economics math — used by the UI and (later) the fee bot.
//   feesGenerated = volumeUsd * FEE_RATE            (0.03% of trading volume)
//   feesToKeys    = feesGenerated * FEE_SHARE_TO_KEYS
//   feePerKeySol  = (feesToKeys / solPriceUsd) / max(keys, 1)
//   keyValueSol   = baseKeySol + feePerKeySol

